const { readFileSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { Script } = require('node:vm');

const root = resolve(__dirname, '..');
const modules = ['config', 'metadata', 'styles', 'helpers', 'settings', 'scan', 'cleanup', 'ui', 'init'];
const header = readFileSync(resolve(root, 'src/userscript-header.txt'), 'utf8').trimEnd();
const { version } = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
if (!header.includes(`// @version      ${version}\n`)) throw new Error('Userscript and package.json versions must match.');
const body = modules.map(name => readFileSync(resolve(root, `src/${name}.js`), 'utf8').trimEnd())
    .join('\n\n').split('\n').map(line => line ? `    ${line}` : '').join('\n');
const output = `${header}\n\n// Generated by npm run build. Edit src/ instead.\n(function () {\n    'use strict';\n\n${body}\n})();\n`;
new Script(output, { filename: 'Steam-License-Cleanup.user.js' });
const target = resolve(root, 'Steam-License-Cleanup.user.js');
if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== output) {
        console.error('The installable userscript is outdated. Run npm run build.');
        process.exitCode = 1;
    }
} else {
    writeFileSync(target, output);
}
